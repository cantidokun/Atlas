def report_dict(report: Any) -> Dict[str, Any]:
    """The SceneReport-shaped dict the merge pass consumes (same form the pinned driver builds)."""
    payload = report.to_json_compatible()
    payload["digest"] = report.digest()
    payload["report_format_version"] = REPORT_FORMAT_VERSION
    return payload


def scene_input_dict(payload: Dict[str, Any]) -> Dict[str, Any]:
    """The SCENE-INPUT grammar for the real planner (no extraction-only schema_version field)."""
    out = dict(payload)
    out.pop("schema_version", None)
    return out


def real_merge_plan(report: Any, payload: Dict[str, Any]) -> Any:
    """Run the REAL planner's explicit merge pass (the sole merge producer) over one report."""
    from planning.blender.correction_planner import plan_merge_vertex_correction

    return plan_merge_vertex_correction(report_dict(report), scene_input_dict(payload),
                                        profile=PLANNER_PROFILE)
