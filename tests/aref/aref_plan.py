"""A-REF plan artifact module: P1/P2/P3 construction, canonical serialization, identity binding.

Design authority: R4F section 9.10 (plan provenance, construction rules, shared artifact,
ownership), 16.2 (duplicate cases), 25 (fixture plan rules).

The plan is generated by the REAL planner and consumed by the EXISTING executor. This module
reproduces the pinned driver's documented construction patterns exactly:
  P2 selected_pair  — w1_w1b_face_removal_live_script.py:575-588;
  P3 keep_only_target — w1_w1b_face_removal_live_script.py:332-346;
  re-point (16.2(b)) — remap_plan semantics, :319-345.
No plan field is hand-forged; plan_id is recomputed by the CorrectionPlan contract
(correction_contract.py:242-252).
"""

